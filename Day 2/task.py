# Subscripting
print("Hello"[0])

# Concatenation
print("Hello" + "World")

# Integer = Whole Numbers
print(123 + 456)

# Large Integers
print(123_456_789)

# Float = Decimal Numbers
print(3.14)

# Boolean = True or False
print(True)
print(False)

# Type Checking
print(type("Hello"))
print(type(2342))
print(type(2343242.323))
print(type(True))

# Type Conversion or Type Casting
print(str(2342))
print(int(2343242.323))
print(float(True))
print(str(True))
print(int(False))
print(float(False))
print(str(False))
print(int(True))
print(float(True))
print(str(True))

